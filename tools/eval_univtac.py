#!/usr/bin/env python
"""Closed-loop evaluation of TacInno-VLA on UniVTAC.

The evaluation runs the benchmark's own evaluator (``scripts/eval_policy.py`` of a UniVTAC checkout) with the
TacInno-VLA client as its policy; the client queries a policy server started with ``tools/serve_policy.py``.

1. Install the client into the UniVTAC checkout (once)::

       python tools/eval_univtac.py install --univtac-root /path/to/UniVTAC

   This copies the client to ``policy/TacInnoVLA/``, writes one deploy config per task (and a tactile-off variant),
   and applies ``tools/univtac/eval_policy_protocol.patch`` to ``scripts/eval_policy.py``. The patch only adds
   per-episode records (``episodes.json``), an optional action-limit scale and a headless switch; the episode loop,
   seeds and success checks are the benchmark's.

2. Start a policy server for the task (separate shell, GPU machine), then evaluate 100 episodes with twice the default
   action limit, as in the paper::

       python tools/eval_univtac.py run --univtac-root /path/to/UniVTAC --task lift_can --host <server> --port 8000

   Add ``--tactile-off`` for the tactile-off test.

3. Summarize (success rate over the first 100 valid episodes from seed 1000000)::

       python tools/eval_univtac.py summarize /path/to/UniVTAC/eval_result/TacInnoVLA/lift_can/deploy_lift_can

   and compare two policies on paired seeds with ``tools/analysis/mcnemar.py``.
"""
from __future__ import annotations

import argparse
import os
import os.path as osp
import shutil
import subprocess
import sys

REPO = osp.dirname(osp.dirname(osp.abspath(__file__)))
sys.path.insert(0, REPO)

from tacinno.evaluation.results import PAPER_SEEDS, first_results, first_valid_seeds, success_rate  # noqa: E402

TASKS = ("insert_hole", "insert_tube", "lift_bottle", "lift_can", "pull_out_key", "put_bottle_in_shelf")
#: action execution horizon of the released checkpoints (rows of the 32-step chunk executed per inference)
REPLAN = {"insert_hole": 31, "insert_tube": 31, "lift_bottle": 10, "lift_can": 10, "pull_out_key": 31,
          "put_bottle_in_shelf": 31}
PATCH = osp.join(REPO, "tools", "univtac", "eval_policy_protocol.patch")
PATCH_MARKER = "TacInno protocol"
CLIENT_FILES = ("univtac_client.py", "msgpack_numpy.py")

DEPLOY_TEMPLATE = """\
# TacInno-VLA client for UniVTAC ({task}); generated by tools/eval_univtac.py
policy_name: {policy_name}
# policy server address, overridden by the environment variables TACINNO_HOST / TACINNO_PORT
host: {host}
port: {port}
# action execution horizon: rows of the 32-step chunk executed per inference
replan: {replan}
instruction_type: seen
# the server holds the task instruction
instuction_file: null
seed: 0
# optional: suffix of the checkpoint path the server must announce
expect_checkpoint: ""
# tactile-off test; no_contact_frame: .npz with l_depth, l_marker, r_depth, r_marker (default: first frame of the episode)
tactile_off: {tactile_off}
no_contact_frame: null
"""


def _univtac_root(path: str) -> str:
    root = osp.abspath(osp.expanduser(path))
    if not osp.isfile(osp.join(root, "scripts", "eval_policy.py")) or not osp.isdir(osp.join(root, "policy")):
        raise SystemExit(f"{root} does not look like a UniVTAC checkout (scripts/eval_policy.py, policy/)")
    return root


def cmd_install(args: argparse.Namespace) -> None:
    root = _univtac_root(args.univtac_root)
    dst = osp.join(root, "policy", args.policy_name)
    os.makedirs(dst, exist_ok=True)
    src = osp.join(REPO, "tacinno", "evaluation")
    for name in CLIENT_FILES:
        shutil.copy2(osp.join(src, name), osp.join(dst, name))
    with open(osp.join(dst, "__init__.py"), "w") as f:
        f.write("from .univtac_client import Policy\n\n__all__ = [\"Policy\"]\n")
    for task in TASKS:
        for suffix, off in (("", "false"), ("_tactile_off", "true")):
            with open(osp.join(dst, f"deploy_{task}{suffix}.yml"), "w") as f:
                f.write(DEPLOY_TEMPLATE.format(task=task, policy_name=args.policy_name, host=args.host,
                                               port=args.port, replan=REPLAN[task], tactile_off=off))
    print(f"client and deploy configs written to {dst}")

    if args.no_patch:
        return
    script = osp.join(root, "scripts", "eval_policy.py")
    with open(script) as f:
        if PATCH_MARKER in f.read():
            print(f"{script} is already patched")
            return
    check = subprocess.run(["patch", "-p1", "--dry-run", "-i", PATCH], cwd=root, capture_output=True, text=True)
    if check.returncode != 0:
        raise SystemExit(f"the protocol patch does not apply cleanly to {script}:\n{check.stdout}{check.stderr}\n"
                         f"Apply {PATCH} by hand (it only adds episode records and the action-limit scale).")
    subprocess.run(["patch", "-p1", "-i", PATCH], cwd=root, check=True)
    print(f"patched {script}")


def cmd_run(args: argparse.Namespace) -> None:
    root = _univtac_root(args.univtac_root)
    suffix = "_tactile_off" if args.tactile_off else ""
    deploy = f"{args.policy_name}/deploy_{args.task}{suffix}"
    if not osp.isfile(osp.join(root, "policy", deploy + ".yml")):
        raise SystemExit(f"missing policy/{deploy}.yml; run `tools/eval_univtac.py install` first")
    env = dict(os.environ, UNIVTAC_STEP_LIM_SCALE=str(args.time_limit_scale), UNIVTAC_LIVESTREAM=str(args.livestream))
    if args.host:
        env["TACINNO_HOST"] = args.host
    if args.port:
        env["TACINNO_PORT"] = str(args.port)
    cmd = [args.python, "-u", "scripts/eval_policy.py", args.task, args.task_config, deploy,
           "--start_seed", str(args.start_seed), "--total_num", str(args.episodes)] + list(args.extra)
    print("running:", " ".join(cmd), flush=True)
    raise SystemExit(subprocess.call(cmd, cwd=root, env=env))


def cmd_summarize(args: argparse.Namespace) -> None:
    seeds = first_valid_seeds(first_results(args.results), args.start_seed, args.num)
    res = first_results(args.results, seeds)
    s = success_rate(res, seeds)
    span = f"seeds {seeds[0]}-{seeds[-1]}" if seeds else "no seeds"
    print(f"{s['valid']} valid episodes ({span}): success {s['success']}/{s['valid']} = {100 * s['rate']:.1f}%")
    if s["valid"] < args.num:
        print(f"only {s['valid']} of {args.num} episodes finished so far")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("install", help="install the TacInno-VLA client into a UniVTAC checkout")
    p.add_argument("--univtac-root", required=True)
    p.add_argument("--policy-name", default="TacInnoVLA")
    p.add_argument("--host", default="127.0.0.1")
    p.add_argument("--port", type=int, default=8000)
    p.add_argument("--no-patch", action="store_true", help="do not patch scripts/eval_policy.py")
    p.set_defaults(func=cmd_install)

    p = sub.add_parser("run", help="evaluate one task with the official UniVTAC evaluator")
    p.add_argument("--univtac-root", required=True)
    p.add_argument("--task", required=True, choices=TASKS)
    p.add_argument("--policy-name", default="TacInnoVLA")
    p.add_argument("--host", default=None, help="policy server host (default: the deploy config)")
    p.add_argument("--port", type=int, default=None, help="policy server port (default: the deploy config)")
    p.add_argument("--episodes", type=int, default=len(PAPER_SEEDS))
    p.add_argument("--start-seed", type=int, default=PAPER_SEEDS.start)
    p.add_argument("--time-limit-scale", type=float, default=2.0, help="action-limit scale (2 in the paper)")
    p.add_argument("--tactile-off", action="store_true", help="tactile-off test")
    p.add_argument("--task-config", default="demo", help="UniVTAC task config (task_config/<name>.yml)")
    p.add_argument("--livestream", type=int, default=0, help="Isaac Sim livestream mode (0 = headless)")
    p.add_argument("--python", default=sys.executable, help="python of the UniVTAC / Isaac Sim environment")
    p.add_argument("extra", nargs=argparse.REMAINDER, help="extra arguments for eval_policy.py (after --)")
    p.set_defaults(func=cmd_run)

    p = sub.add_parser("summarize", help="success rate from episodes.json files or run directories")
    p.add_argument("results", nargs="+", help="episodes.json files or directories containing them")
    p.add_argument("--start-seed", type=int, default=PAPER_SEEDS.start)
    p.add_argument("--num", type=int, default=len(PAPER_SEEDS))
    p.set_defaults(func=cmd_summarize)

    args = parser.parse_args()
    if getattr(args, "extra", None) and args.extra[:1] == ["--"]:
        args.extra = args.extra[1:]
    args.func(args)


if __name__ == "__main__":
    main()
